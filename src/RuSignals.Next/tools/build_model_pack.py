"""Convert the selected RUS models and emit the matching C# lens catalogue."""
import argparse, hashlib, json
from collections import defaultdict
from pathlib import Path
import numpy as np
from convert_assets import shape_parts, obj_parts, write_mesh, export_obj, ace_png

MODELS = [
    ('shunting',None,['MoonWhite','Blue']),
    ('mast','T_Signal_Head_YGR-new.s',['Yellow','Green','Red']),
    ('entry','T_Signal_Head_YGR_YW-new.s',['Yellow','Green','Red','Yellow2','MoonWhite']),
    ('exit','T_Signal_Head_YG_RW-new.s',['Yellow','Green','Red','MoonWhite']),
    ('exit_mainline','T_Signal_Head_YGR_GW-new.s',['Yellow','Green','Red','Green2','MoonWhite']),
    ('exit_small_two_yellows','T_Signal_Small_YGY_WR-new.s',['Yellow','Green','MoonWhite','Yellow2','Red']),
    ('exit_small','T_Signal_Small_YGW_Rx-new.s',['Yellow','Green','Red','MoonWhite','Unused']),
    ('shunting_mast','T_Signal_Head_WB-new.s',['MoonWhite','Blue']),
    ('distant','T_Signal_Head_YG.s',['Green','Yellow']),
    ('repeater','T_Signal_Head_G.s',['Green']),
    ('junction','T_Signal_Head_YGR_YGW-new.s',['Yellow','Green','Red','Yellow2','Green2','MoonWhite']),
    ('turntable','T_Signal_Small_WR-new.s',['MoonWhite','Red']),
]

def lens_fans(parts):
    """Identify original convex 16-triangle lenses by their shared central vertex."""
    fans=[]
    for part_index,part in enumerate(parts):
        points,faces=part['p'],part['f'];attached=defaultdict(set)
        for i,tri in enumerate(faces):
            for v in tri:attached[tuple(np.round(points[v],5))].add(i)
        for center,indices in attached.items():
            if len(indices)!=16:continue
            delta=points[faces[sorted(indices)]]-center
            radius=np.linalg.norm(delta[:,:,:2],axis=2).max()
            if .06<radius<.16 and -.025<delta[:,:,2].min()<-.001 and delta[:,:,2].max()<.0001:
                fans.append(dict(part=part_index,indices=sorted(indices),center=np.array(center)))
    return sorted(fans,key=lambda f:(-round(f['center'][1],3),round(f['center'][0],3)))

def split_fans(parts,names):
    fans=lens_fans(parts)
    assert len(fans)==len(names),(len(fans),names)
    result=[];lamps=[]
    def subset(part,mask,name):
        faces=part['f'][mask];used,inverse=np.unique(faces,return_inverse=True)
        return dict(part,name=name,p=part['p'][used],n=part['n'][used],uv=part['uv'][used],f=inverse.reshape(-1,3))
    masks=[np.ones(len(p['f']),dtype=bool) for p in parts]
    for name,fan in zip(names,fans):
        i=fan['part'];mask=np.zeros(len(parts[i]['f']),dtype=bool);mask[fan['indices']]=True
        assert masks[i][mask].all(), 'Overlapping lens triangles'
        masks[i][mask]=False;result.append(subset(parts[i],mask,name))
        if name!='Unused':
            lamps.append(dict(name=name,position=(fan['center']+np.array([0,0,.02])).tolist(),triangles=16))
    for i,part in enumerate(parts):
        if masks[i].any():result.append(subset(part,masks[i],'Body_'+str(i)+'_'+part['name']))
    assert sum(len(p['f']) for p in parts)==sum(len(p['f']) for p in result)
    return result,lamps

def oriented_triangles(parts):
    # Float32 is the runtime format. Canonicalize only cyclic rotations;
    # reversing a face must change its signature and fail verification.
    result=[]
    for p in parts:
        for face in p['f']:
            vertices=[tuple(v) for v in p['p'][face].astype('<f4')]
            result.append(min(tuple(vertices[i:]+vertices[:i]) for i in range(3)))
    return sorted(result)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ru',type=Path,default=Path(r'D:\ru'))
    parser.add_argument('--obj',type=Path,required=True)
    parser.add_argument('--out',type=Path,required=True)
    args=parser.parse_args();route=args.ru/'ROUTES/TestRoute_RUS';args.out.mkdir(parents=True,exist_ok=True)
    report=dict(version='1.4.0',models={},textures={},placement_offsets_y={'mast':-.80,'dwarf':-.30},
        winding='source order preserved; one uniform reversal for reflected MSTS coordinates')
    code=['// Generated by tools/build_model_pack.py. Original lens centers in metres.',
          'namespace RuSignals;', 'internal static class RuModelCatalog','{']
    for key,filename,names in MODELS:
        source=route/'SHAPES'/filename if filename else args.obj
        original=shape_parts(source) if filename else obj_parts(source)
        ground=min(p['p'][:,1].min() for p in original)
        for p in original:p['p'][:,1]-=ground
        parts,lamps=split_fans(original,names)
        assert oriented_triangles(parts)==oriented_triangles(original), 'Source winding changed'
        write_mesh(parts,args.out/(key+'.rsm'));export_obj(parts,args.out/(key+'.obj'))
        points=np.concatenate([p['p'] for p in parts])
        depth=.80 if points[:,1].max()>2 else .30
        report['models'][key]=dict(source=str(source.resolve()),sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
            ground_offset=float(ground),placement_offset_y=-depth,parts=len(parts),vertices=len(points),triangles=sum(len(p['f']) for p in parts),
            min=points.min(0).tolist(),max=points.max(0).tolist(),lenses=lamps,source_triangle_order_verified=True)
        for part in parts:
            texture=part['texture']
            if texture not in report['textures']:report['textures'][texture]=ace_png(route/'TEXTURES'/Path(texture).with_suffix('.ace'),args.out/texture)
        code.append('    internal static readonly ModelSpec '+key+' = new ModelSpec("'+key+'", '+format(depth,'.2f')+'f,')
        for i,lamp in enumerate(lamps):
            xyz=', '.join(format(v,'.9g')+'f' for v in lamp['position'])
            code.append('        new LensSpec("'+lamp['name']+'", '+xyz+')'+(');' if i==len(lamps)-1 else ','))
    code+=['    internal static readonly ModelSpec[] All = { '+', '.join(k for k,_,_ in MODELS)+' };','}']
    (args.out.parent/'ModelCatalog.Generated.cs').write_text('\n'.join(code)+'\n',encoding='utf-8')
    (args.out/'conversion-report.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps({k:{'triangles':v['triangles'],'lamps':[l['name'] for l in v['lenses']]} for k,v in report['models'].items()}))

if __name__=='__main__':main()
